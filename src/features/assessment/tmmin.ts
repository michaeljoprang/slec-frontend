// Helper to calculate overtime penalty
// 481-490 sec => -1
// 491-500 sec => -2
// ... up to 600 sec => -12
export function calculateTmminOvertimePenalty(elapsedSeconds: number): number {
  if (elapsedSeconds <= 480) return 0;
  if (elapsedSeconds > 600) return 12; // Cap at 12 before DISQUALIFIED takes over

  const overtime = elapsedSeconds - 480;
  return Math.ceil(overtime / 10);
}

export function determineTmminResult(
  totalScore: number,
  elapsedSeconds: number
): 'PASS' | 'FAIL' | 'DISQUALIFIED' {
  if (elapsedSeconds > 600) {
    return 'DISQUALIFIED';
  }
  if (totalScore >= 70) {
    return 'PASS';
  }
  return 'FAIL';
}

